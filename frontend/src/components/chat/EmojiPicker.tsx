// Memoized emoji button component for better performance
const EmojiButton = React.memo(({ emoji, onSelect }: { emoji: string; onSelect: (emoji: string) => void }) => {
  const handleClick = useCallback(() => {
    onSelect(emoji)
  }, [emoji, onSelect])

  return (
    <button
      onClick={handleClick}
      className="w-8 h-8 flex items-center justify-center text-lg hover:bg-gray-100 rounded transition-colors active:scale-95"
      title={emoji}
      type="button"
      aria-label={`Emoji: ${emoji}`}
    >
      {emoji}
    </button>
  )
}, (prevProps, nextProps) => {
  // Only re-render if emoji or onSelect changes
  return prevProps.emoji === nextProps.emoji && prevProps.onSelect === nextProps.onSelect
})

EmojiButton.displayName = 'EmojiButton'

